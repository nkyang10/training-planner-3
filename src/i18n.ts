/** A value interpolated into a message via `{name}`. */
export type MessageVars = Readonly<Record<string, string | number>>;

/**
 * Locale-aware date formatting built on `Intl`, so weekday and month names follow the active locale instead of
 * hard-coded English arrays. Day strings are `YYYY-MM-DD`; all formatting is pinned to UTC so a calendar cell shows
 * the same day everywhere regardless of the server's timezone.
 */
export interface DateFormat {
  /** "Mon, 5 Jan 2026" style label for a `YYYY-MM-DD` day. */
  dayLabel(day: string): string;
  /** "Sat, 21 Nov" style compact label with weekday, for a `YYYY-MM-DD` day. */
  weekdayDate(day: string): string;
  /** "5 Jan" style compact date for a `YYYY-MM-DD` day. */
  shortDate(day: string): string;
  /** "January 2026" for a `YYYY-MM` month. */
  monthLabel(month: string): string;
  /** Short month name ("Jan") for a `YYYY-MM` month. */
  shortMonthName(month: string): string;
  /** Monday-first short weekday names for the calendar header. */
  weekdays(): string[];
  /** January–December month names (for chart axes and pickers). */
  monthNames(): string[];
}

function parseDay(day: string): Date {
  return new Date(`${day}T00:00:00.000Z`);
}

/**
 * The BCP-47 tag handed to `Intl` for date formatting. The UI locale code drives `<html lang>` and translation, but
 * date layout follows regional convention: Hong Kong reads day-before-month ("7 Nov 2026"), so English is pinned to
 * `en-GB` rather than the `en`→en-US default that would render "Nov 7, 2026".
 */
const INTL_DATE_TAG: Record<Locale, string> = { en: "en-GB", "zh-HK": "zh-HK" };

function createDateFormat(locale: Locale): DateFormat {
  const tag = INTL_DATE_TAG[locale];
  const dayLabelFmt = new Intl.DateTimeFormat(tag, { weekday: "short", day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
  const weekdayOnlyFmt = new Intl.DateTimeFormat(tag, { weekday: "short", timeZone: "UTC" });
  const weekdayDateFmt = new Intl.DateTimeFormat(tag, { weekday: "short", day: "numeric", month: "short", timeZone: "UTC" });
  const shortDateFmt = new Intl.DateTimeFormat(tag, { day: "numeric", month: "short", timeZone: "UTC" });
  const monthLabelFmt = new Intl.DateTimeFormat(tag, { month: "long", year: "numeric", timeZone: "UTC" });
  const shortMonthFmt = new Intl.DateTimeFormat(tag, { month: "short", timeZone: "UTC" });
  const weekdayFmt = new Intl.DateTimeFormat(tag, { weekday: "short", timeZone: "UTC" });
  const monthNameFmt = new Intl.DateTimeFormat(tag, { month: "long", timeZone: "UTC" });
  return {
    dayLabel: (day) => dayLabelFmt.format(parseDay(day)),
    // English keeps the app's day-before-month order with the comma its long labels use; Chinese uses the locale's own.
    weekdayDate: (day) => (locale === "en" ? `${weekdayOnlyFmt.format(parseDay(day))}, ${shortDateFmt.format(parseDay(day))}` : weekdayDateFmt.format(parseDay(day))),
    shortDate: (day) => shortDateFmt.format(parseDay(day)),
    monthLabel: (month) => monthLabelFmt.format(parseDay(`${month}-01`)),
    shortMonthName: (month) => shortMonthFmt.format(parseDay(`${month}-01`)),
    // 2024-01-01 is a Monday; stepping 7 days yields a Monday-first short week regardless of locale.
    weekdays: () => Array.from({ length: 7 }, (_, i) => weekdayFmt.format(new Date(Date.UTC(2024, 0, 1 + i)))),
    monthNames: () => Array.from({ length: 12 }, (_, i) => monthNameFmt.format(new Date(Date.UTC(2024, i, 1)))),
  };
}

export interface Translator {
  readonly locale: Locale;
  readonly dir: "ltr" | "rtl";
  /** Locale-aware date/weekday/month formatting bound to this translator's locale. */
  readonly date: DateFormat;
  /** Translate `key`, interpolating `{name}` placeholders from `vars`. Falls back to English, then to the key. */
  t(key: MessageKey, vars?: MessageVars): string;
  /** The ordered starter prompts for the coach rail, localized. */
  starters(): string[];
}

/**
 * Plural block: `{count, one{singular} other{plural}}`. Picks `one` when count is exactly 1 (falls back to `other`
 * when there is no `one` branch). Chinese catalogs simply repeat the same text in both branches.
 */
/**
 * A plural branch body: plain text with at most one level of nested `{token}`, e.g. the `{count} run` inside
 * `{count, one{{count} run} other{{count} runs}}`. Kept as a string fragment so the matcher can be composed.
 */
const PLURAL_BRANCH = String.raw`(?:[^{}]|\{[^{}]*\})*`;

/** `{name, one{…} other{…}}` with one level of nesting allowed inside each branch. The two branch bodies are captured. */
const PLURAL_SOURCE = String.raw`\{(\w+),\s*one\{(${PLURAL_BRANCH})\}\s*other\{(${PLURAL_BRANCH})\}\s*\}`;

/** Pick the one/other branch for a plural block, then expand every `{token}` placeholder inside it. */
function resolvePlural(oneText: string, otherText: string, countKey: string, vars?: MessageVars): string {
  const rawCount = vars?.[countKey];
  const count = typeof rawCount === "number" ? rawCount : Number(rawCount);
  const chosen = count === 1 && oneText.length > 0 ? oneText : otherText;
  return chosen.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars?.[name];
    return value === undefined ? whole : String(value);
  });
}

function interpolate(template: string, vars?: MessageVars): string {
  // Plural blocks first (they contain braces), then plain {name} tokens; a fresh matcher avoids lastIndex state.
  let out = template.replace(new RegExp(PLURAL_SOURCE, "g"), (block, countKey: string, oneText: string, otherText: string) =>
    resolvePlural(oneText, otherText, countKey, vars));
  out = out.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars?.[name];
    return value === undefined ? whole : String(value);
  });
  return out;
}

export function createTranslator(locale: Locale): Translator {
  const catalog = CATALOGS[locale];
  const fallback = CATALOGS[DEFAULT_LOCALE];
  const meta = localeMeta(locale);
  return {
    locale,
    dir: meta.dir,
    date: createDateFormat(locale),
    t(key, vars) {
      const template = catalog[key] ?? fallback[key] ?? key;
      return interpolate(template, vars);
    },
    starters() {
      return [this.t("coach.starter1"), this.t("coach.starter2"), this.t("coach.starter3")];
    },
  };
}

/** The always-available English translator, used as a module default and for tooling. */
export const defaultTranslator: Translator = createTranslator(DEFAULT_LOCALE);

/** Cookie the web shell uses to remember a runner's chosen language across every page. */
export const LOCALE_COOKIE = "milebook_lang";

/** Map a browser `Accept-Language` header onto a supported locale (best-effort, prefix matched). */
function matchAcceptLanguage(header: string | undefined): Locale | undefined {
  if (header === undefined || header.trim().length === 0) return undefined;
  for (const part of header.split(",")) {
    const tag = part.split(";")[0]?.trim().toLowerCase();
    if (tag === undefined || tag.length === 0) continue;
    if (tag.startsWith("zh-hant") || tag === "zh-hk" || tag === "zh-mo" || tag === "zh") return "zh-HK";
    if (tag.startsWith("en")) return "en";
  }
  return undefined;
}

/**
 * Resolve the locale for a request: an explicit cookie wins, then the browser's Accept-Language, then English.
 * `cookieValue` is the raw value read from the request's `milebook_lang` cookie.
 */
export function resolveLocale(cookieValue: string | undefined, acceptLanguage: string | undefined): Locale {
  if (isLocale(cookieValue)) return cookieValue;
  return matchAcceptLanguage(acceptLanguage) ?? DEFAULT_LOCALE;
}

/** Build a `Translator` directly from a resolved locale. */
export function translatorFor(locale: Locale): Translator {
  return createTranslator(locale);
}

/**
 * The subset of the catalog consumed by inline client scripts, keyed by the name after the `js.` prefix (so
 * `js.confirm` is exposed as `confirm`). Derived from the catalog keys, so adding a `js.*` key automatically ships
 * it to the client with no extra wiring.
 */
export function clientStrings(locale: Locale): Record<string, string> {
  const messages = CATALOGS[locale] ?? CATALOGS[DEFAULT_LOCALE];
  const out: Record<string, string> = {};
  for (const key of Object.keys(en) as MessageKey[]) {
    if (key.startsWith("js.")) out[key.slice(3)] = messages[key];
    // The change card renders server-side and in the coach panel; both use the same copy.
    else if (key.startsWith("changes.")) out[key] = messages[key];
  }
  return out;
}

/** A long-lived cookie remembering the runner's chosen language. */
export function languageCookie(code: Locale): string {
  return `${LOCALE_COOKIE}=${encodeURIComponent(code)}; SameSite=Lax; Path=/; Max-Age=${60 * 60 * 24 * 365}`;
}
