/**
 * Internationalisation core for the web surface.
 *
 * Design goals:
 *  - English is the source of truth and the fallback. Every key that exists in a translation must exist here first.
 *  - Adding a language is one new catalog object plus one entry in `LOCALES`; nothing else changes.
 *  - The web shell (`layout`) is the single place that resolves a request's locale and threads a `Translator`
 *    through every rendered page, so all pages — including the shared chrome, the footer switcher and `<html lang>` —
 *    switch together.
 *  - Catalogs are a flat, dotted-key record: easy to diff, easy to audit for missing translations, and the key type
 *    is derived from `en` so a typo is a compile error.
 */

/** BCP 47 language tags this build ships. Add future tags here and register them in `LOCALES`. */
export type Locale = "en" | "zh-HK";

/** The default locale, and the fallback used for a missing key. */
export const DEFAULT_LOCALE: Locale = "en";

export interface LocaleMeta {
  /** BCP 47 tag, also the `lang` attribute value. */
  readonly code: Locale;
  /** Name in its own language, shown on the switcher button. */
  readonly nativeName: string;
  /** English name, shown as a tooltip / secondary label. */
  readonly englishName: string;
  readonly dir: "ltr" | "rtl";
}

/** Registration order — the switcher renders these in order. Put new languages after the existing two. */
export const LOCALES: readonly LocaleMeta[] = [
  { code: "en", nativeName: "English", englishName: "English", dir: "ltr" },
  { code: "zh-HK", nativeName: "繁體中文（香港）", englishName: "Chinese (Hong Kong)", dir: "ltr" },
];

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && LOCALES.some((meta) => meta.code === value);
}

export function localeMeta(code: Locale): LocaleMeta {
  return LOCALES.find((entry) => entry.code === code) ?? LOCALES[0] as LocaleMeta;
}

